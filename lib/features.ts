/**
 * Переключатели функций, которые ещё находятся в разработке.
 *
 * Значение читается только на сервере: клиент получает флаг через API.
 * Это позволяет выключить статистику в Dokploy, не пересобирая клиентские
 * бандлы и не раскрывая переменную через NEXT_PUBLIC_*.
 */
export function isRatingVisible(): boolean {
    return (process.env.SHOW_RAITING ?? "").trim().toLowerCase() === "true";
}
